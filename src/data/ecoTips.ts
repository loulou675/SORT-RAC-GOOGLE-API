export function getEcoTip(code: string | undefined) {
  return ecoTips.find((entry) => entry.code === code && entry.isActive)
}

export function ecoTipMatchesItem(tip: EcoTip, itemCode: string, materialCode: MaterialCode) {
  return tip.itemCode === itemCode
    || tip.itemCodes?.includes(itemCode)
    || tip.materialCode === materialCode
}

function tip(input: Omit<EcoTip, 'verificationStatus' | 'isActive'>): EcoTip {
  return {
    ...input,
    verificationStatus: 'PENDING_CONFIRMATION',
    isActive: true,
  }
}
